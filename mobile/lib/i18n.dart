const uiLanguages = {'en': 'English', 'bn': 'বাংলা'};

String tr(String lang, String key, [Map<String, Object> vars = const {}]) {
  final s = _strings[lang]?[key] ?? _strings['en']![key] ?? key;
  return s.replaceAllMapped(RegExp(r'\{(\w+)\}'), (m) {
    final v = vars[m[1]];
    if (v == null) return '';
    return v is num ? digits(v, lang) : '$v';
  });
}
